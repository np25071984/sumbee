/// SplitMix64: a small seedable generator. Swift's own `SystemRandomNumberGenerator` can't be seeded,
/// and a session is saved as its seed, not its deck (IMPLEMENTATION.md §3.5), so the same seed must
/// always deal the same deck.
public struct SeededRandom: RandomNumberGenerator, Sendable {
    private var state: UInt64

    public init(seed: UInt64) {
        state = seed
    }

    public mutating func next() -> UInt64 {
        state &+= 0x9E37_79B9_7F4A_7C15
        var z = state
        z = (z ^ (z >> 30)) &* 0xBF58_476D_1CE4_E5B9
        z = (z ^ (z >> 27)) &* 0x94D0_49BB_1331_11EB
        return z ^ (z >> 31)
    }
}
